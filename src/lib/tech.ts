const key = (name: string) => name.toLowerCase().replace(/[\s.\-_/]/g, "");
const byKey = new Map(ICONS.flatMap(([names, icon]) => names.map((n) => [n, icon] as const)));

export type Tech = { name: string; path?: string; hex?: string };

export function tech(name: string): Tech {
  const icon = byKey.get(key(name));
  return icon ? { name, path: icon.path, hex: icon.hex } : { name };
}

export const techKey = key;
